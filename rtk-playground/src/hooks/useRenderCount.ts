import { useRef } from 'react';

/**
 * Считает, сколько раз компонент отрендерился.
 *
 * ПОЧЕМУ useRef, А НЕ useState:
 * useState вызвал бы новый рендер при инкременте → бесконечный цикл.
 * useRef хранит значение между рендерами и НЕ триггерит перерисовку.
 *
 * ПОЧЕМУ НЕ useEffect:
 * useEffect считал бы «сколько раз эффект отработал после коммита»,
 * а нам нужны именно рендеры — включая те, что React отбросил.
 *
 * Предупреждение: в React 18 StrictMode в dev-режиме компоненты рендерятся
 * дважды намеренно. Поэтому числа будут чётными — сравнивай их между собой,
 * а не смотри на абсолютное значение.
 */
export function useRenderCount(): number {
  const count = useRef(0);
  count.current += 1;
  return count.current;
}
