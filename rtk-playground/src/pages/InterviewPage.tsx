const TOPICS = ['Все', ...Array.from(new Set(QUESTIONS.map((q) => q.topic)))];

export function InterviewPage(): JSX.Element {
  const [topic, setTopic] = useState('Все');
  const [openAll, setOpenAll] = useState(false);

  const visible = topic === 'Все' ? QUESTIONS : QUESTIONS.filter((q) => q.topic === topic);

  return (
    <ConceptPage
      title="Вопросы с собеседований"
      lead={`${QUESTIONS.length} вопросов ровно по темам этого стенда. Сначала ответь сам, потом раскрой.`}
    >
      <div className="row" style={{ marginBottom: 16 }}>
        {TOPICS.map((t) => (
          <button key={t} className={topic === t ? 'primary' : ''} onClick={() => setTopic(t)}>
            {t}
          </button>
        ))}
        <button onClick={() => setOpenAll((v) => !v)}>
          {openAll ? 'Свернуть все' : 'Раскрыть все'}
        </button>
      </div>

      <section className="card">
        {visible.map((qa) => (
          // key включает openAll, чтобы принудительное раскрытие/сворачивание
          // пересоздало <details> — иначе атрибут open не переопределит
          // состояние, которое пользователь уже поменял руками.
          <details className="qa" key={`${qa.q}-${String(openAll)}`} open={openAll}>
            <summary>
              {qa.q} <span className="badge" style={{ marginLeft: 8 }}>{qa.topic}</span>
            </summary>
            <div>{qa.a}</div>
          </details>
        ))}
      </section>

      <section className="card warn">
        <h3>Вопросы, которые задают «на подумать»</h3>
        <ul className="tight">
          <li>Зачем вообще Redux, если есть Context + useReducer? (ответ: DevTools с time-travel,
            middleware, подписка в обход дерева, единый слой кеша и общая дисциплина)</li>
          <li>Что бы ты выбрал сегодня для нового проекта: RTK Query, React Query или SWR?
            (честный ответ: если Redux уже есть — RTK Query, иначе React Query почти всегда
            проще)</li>
          <li>Где грань между состоянием в Redux и локальным useState? (правило: нужно
            двум и более несвязанным компонентам, или нужно пережить размонтирование —
            в стор; иначе useState)</li>
          <li>Почему Redux Toolkit не спасает от «слишком много состояния в сторе»?</li>
        </ul>
      </section>
    </ConceptPage>
  );
}
